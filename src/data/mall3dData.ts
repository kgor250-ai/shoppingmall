// 3D WAYPOINT NAVIGATION PATHFINDER
// ----------------------------------------------------
export interface NavigationRoute {
  pathPoints: [number, number, number][]
  routeSteps: string[]
  walkTime: string
  distance: string
  floorTransition: {
    type: 'escalator' | 'elevator'
    fromFloor: string
    toFloor: string
  } | null
}

export function calculateMallRoute(
  startLandmarkId: string,
  destinationStore: Store3DData
): NavigationRoute {
  const start = mallLandmarks.find(l => l.id === startLandmarkId) || mallLandmarks[0]
  const startFloor = start.floorId
  const endFloor = destinationStore.floorId

  const getCorridorNodeForFloor = (floor: string) => {
    switch (floor) {
      case 'P2': return 'P2-Center'
      case 'P1': return 'P1-Center'
      case '1': return 'L1-Center'
      case '2': return 'L2-Center'
      case '3': return 'L3-Center'
      case 'G':
      default:
        return 'G-Center'
    }
  }

  const nearestStartCorridor = getCorridorNodeForFloor(startFloor)
  const nearestDestCorridor = getCorridorNodeForFloor(endFloor)

  const startNodeId = 'START_DYNAMIC'
  const destNodeId = 'DEST_DYNAMIC'

  const tempGraph = { ...MOCK_NAV_GRAPH }
  tempGraph[startNodeId] = {
    id: startNodeId,
    point: { x: start.position[0], y: start.position[1], z: start.position[2] },
    connections: [nearestStartCorridor],
  }
  tempGraph[destNodeId] = {
    id: destNodeId,
    point: {
      x: destinationStore.modelPosition[0],
      y: destinationStore.modelPosition[1],
      z: destinationStore.modelPosition[2],
    },
    connections: [nearestDestCorridor],
  }

  if (tempGraph[nearestStartCorridor]) {
    tempGraph[nearestStartCorridor] = {
      ...tempGraph[nearestStartCorridor],
      connections: [...tempGraph[nearestStartCorridor].connections, startNodeId],
    }
  }
  if (tempGraph[nearestDestCorridor]) {
    tempGraph[nearestDestCorridor] = {
      ...tempGraph[nearestDestCorridor],
      connections: [...tempGraph[nearestDestCorridor].connections, destNodeId],
    }
  }

  const rawPath = findPath(startNodeId, destNodeId, tempGraph)
  const pathPoints: [number, number, number][] =
    rawPath.length > 0
      ? rawPath.map(p => [p.x, p.y, p.z])
      : [
          [start.position[0], start.position[1], start.position[2]],
          [destinationStore.modelPosition[0], destinationStore.modelPosition[1], destinationStore.modelPosition[2]],
        ]

  let totalDistUnits = 0
  for (let i = 0; i < pathPoints.length - 1; i++) {
    const dx = pathPoints[i + 1][0] - pathPoints[i][0]
    const dy = pathPoints[i + 1][1] - pathPoints[i][1]
    const dz = pathPoints[i + 1][2] - pathPoints[i][2]
    totalDistUnits += Math.sqrt(dx * dx + dy * dy + dz * dz)
  }

  const distanceMeters = Math.max(35, Math.round(totalDistUnits * 5))
  const walkMinutes = Math.max(1, Math.round(distanceMeters / 65))

  const steps: string[] = []
  steps.push(`Depart from ${start.name}`)
  if (startFloor !== endFloor) {
    const isParking = startFloor === 'P1' || startFloor === 'P2' || endFloor === 'P1' || endFloor === 'P2'
    const transType = isParking ? 'Panoramic Glass Elevator' : 'Central Escalator Bank'
    steps.push(`Proceed to the ${transType} on Level ${startFloor}`)
    steps.push(`Take vertical connection to Level ${endFloor}`)
  }
  steps.push(`Walk along the main promenade corridor towards the ${destinationStore.wing}`)
  steps.push(`Arrive at ${destinationStore.name} (${destinationStore.shopNumber})`)

  return {
    pathPoints,
    routeSteps: steps,
    walkTime: `${walkMinutes} min walk`,
    distance: `${distanceMeters}m`,
    floorTransition:
      startFloor !== endFloor
        ? {
            type: startFloor === 'P1' || startFloor === 'P2' || endFloor === 'P1' || endFloor === 'P2' ? 'elevator' : 'escalator',
            fromFloor: startFloor,
            toFloor: endFloor,
          }
        : null,
  }
}

